-- Counter checkout: one bill per visit/customer holding services, products and
-- package redemptions, editable until it is paid.
--
-- Server-only: RLS on with no policies; staff pages use the service role after
-- their role check. Safe to re-run.

-- 1. Bills ------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.counter_sales (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Printed as INV-000123. BY DEFAULT so imported Tunai Pro bills can keep theirs.
  bill_no             BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  status              TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'paid', 'void')),
  patient_id          UUID REFERENCES public.patients(id) ON DELETE SET NULL,
  appointment_id      UUID REFERENCES public.appointments(id) ON DELETE SET NULL,
  -- Who the receipt is for, kept as it was at the time of the bill.
  customer_name       TEXT NOT NULL CHECK (char_length(customer_name) BETWEEN 1 AND 120),
  customer_phone      TEXT CHECK (customer_phone IS NULL OR char_length(customer_phone) <= 30),
  discount_rm         NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (discount_rm >= 0),
  subtotal_rm         NUMERIC(10,2) NOT NULL DEFAULT 0,
  total_rm            NUMERIC(10,2) NOT NULL DEFAULT 0,
  payment_method      TEXT CHECK (payment_method IS NULL OR payment_method IN
                        ('cash', 'duitnow_qr', 'tng_ewallet', 'card_terminal', 'bank_transfer', 'other')),
  amount_received_rm  NUMERIC(10,2) CHECK (amount_received_rm IS NULL OR amount_received_rm >= 0),
  notes               TEXT CHECK (notes IS NULL OR char_length(notes) <= 500),
  created_by_staff_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  paid_by_staff_id    UUID REFERENCES public.users(id) ON DELETE SET NULL,
  paid_at             TIMESTAMPTZ,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS counter_sales_status_idx ON public.counter_sales (status, created_at DESC);
CREATE INDEX IF NOT EXISTS counter_sales_patient_idx ON public.counter_sales (patient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS counter_sales_appointment_idx ON public.counter_sales (appointment_id);
CREATE INDEX IF NOT EXISTS counter_sales_paid_idx ON public.counter_sales (paid_at DESC) WHERE status = 'paid';

-- 2. Bill lines -------------------------------------------------------------------
-- package_purchase_id has no foreign key on purpose: Ayurvedic Wellness Centre
-- has no packages table yet, and this file is shared by both sites.
CREATE TABLE IF NOT EXISTS public.counter_sale_items (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  sale_id             UUID NOT NULL REFERENCES public.counter_sales(id) ON DELETE CASCADE,
  kind                TEXT NOT NULL CHECK (kind IN ('service', 'product', 'package')),
  treatment_id        UUID REFERENCES public.treatments(id) ON DELETE SET NULL,
  product_id          UUID REFERENCES public.products(id) ON DELETE SET NULL,
  package_purchase_id UUID,
  description         TEXT NOT NULL CHECK (char_length(description) BETWEEN 1 AND 200),
  quantity            INTEGER NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 99),
  unit_price_rm       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (unit_price_rm >= 0),
  line_total_rm       NUMERIC(10,2) GENERATED ALWAYS AS (quantity * unit_price_rm) STORED,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (
    (kind = 'service' AND product_id IS NULL AND package_purchase_id IS NULL) OR
    (kind = 'product' AND product_id IS NOT NULL AND package_purchase_id IS NULL) OR
    (kind = 'package' AND package_purchase_id IS NOT NULL AND unit_price_rm = 0)
  )
);
CREATE INDEX IF NOT EXISTS counter_sale_items_sale_idx ON public.counter_sale_items (sale_id, created_at);

-- A paid or void bill is a record: its lines can't change afterwards.
CREATE OR REPLACE FUNCTION public.counter_sale_items_guard()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
DECLARE v_status TEXT;
BEGIN
  SELECT status INTO v_status FROM public.counter_sales WHERE id = COALESCE(NEW.sale_id, OLD.sale_id);
  IF v_status IS NOT NULL AND v_status <> 'open' THEN
    RAISE EXCEPTION 'bill_closed' USING ERRCODE = '23514';
  END IF;
  RETURN COALESCE(NEW, OLD);
END $$;

DROP TRIGGER IF EXISTS counter_sale_items_guard ON public.counter_sale_items;
CREATE TRIGGER counter_sale_items_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.counter_sale_items
  FOR EACH ROW EXECUTE FUNCTION public.counter_sale_items_guard();

-- 3. Payment: everything happens together or not at all --------------------------
-- Locks the bill, re-adds the lines, checks stock, takes products out of stock,
-- redeems package sessions (linked to the bill's visit) and marks the bill paid.
-- Errors are short codes the app turns into plain messages.
CREATE OR REPLACE FUNCTION public.complete_counter_sale(
  p_sale_id UUID,
  p_staff_id UUID,
  p_method TEXT,
  p_received NUMERIC
)
RETURNS public.counter_sales
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_sale public.counter_sales;
  v_item RECORD;
  v_sub NUMERIC(10,2);
  v_total NUMERIC(10,2);
  v_stock INTEGER;
  v_backorder BOOLEAN;
  -- A plain id, not a package_redemptions row type: that table only exists on
  -- sites with packages, and this function must also install where it doesn't.
  v_redemption_id UUID;
  v_label TEXT;
BEGIN
  SELECT * INTO v_sale FROM public.counter_sales WHERE id = p_sale_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'bill_not_found'; END IF;
  IF v_sale.status <> 'open' THEN RAISE EXCEPTION 'bill_not_open'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.counter_sale_items WHERE sale_id = p_sale_id) THEN
    RAISE EXCEPTION 'bill_empty';
  END IF;

  SELECT COALESCE(SUM(line_total_rm), 0) INTO v_sub FROM public.counter_sale_items WHERE sale_id = p_sale_id;
  v_total := GREATEST(v_sub - v_sale.discount_rm, 0);
  IF v_total > 0 AND p_method IS NULL THEN RAISE EXCEPTION 'payment_method_required'; END IF;
  IF p_method = 'cash' AND (p_received IS NULL OR p_received < v_total) THEN RAISE EXCEPTION 'cash_short'; END IF;
  v_label := 'Bill INV-' || lpad(v_sale.bill_no::text, 6, '0');

  FOR v_item IN
    SELECT * FROM public.counter_sale_items WHERE sale_id = p_sale_id AND kind = 'product' ORDER BY created_at
  LOOP
    SELECT stock_qty, allow_backorder INTO v_stock, v_backorder FROM public.products WHERE id = v_item.product_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'product_missing:%', v_item.description; END IF;
    IF NOT v_backorder AND v_stock < v_item.quantity THEN
      RAISE EXCEPTION 'out_of_stock:%:%', v_item.description, v_stock;
    END IF;
    INSERT INTO public.stock_movements (product_id, movement_type, quantity_delta, reason, actor_id, notes)
    VALUES (v_item.product_id, 'sold', -v_item.quantity, 'counter_sale', p_staff_id, v_label);
  END LOOP;

  FOR v_item IN
    SELECT * FROM public.counter_sale_items WHERE sale_id = p_sale_id AND kind = 'package' ORDER BY created_at
  LOOP
    FOR i IN 1..v_item.quantity LOOP
      -- FROM form: "(fn(...)).col" can run the function more than once.
      SELECT r.id INTO v_redemption_id FROM public.redeem_package_session(v_item.package_purchase_id, p_staff_id, v_label) AS r;
      IF v_sale.appointment_id IS NOT NULL THEN
        UPDATE public.package_redemptions SET appointment_id = v_sale.appointment_id WHERE id = v_redemption_id;
      END IF;
    END LOOP;
  END LOOP;

  UPDATE public.counter_sales
  SET status = 'paid',
      subtotal_rm = v_sub,
      total_rm = v_total,
      payment_method = CASE WHEN v_total > 0 THEN p_method ELSE NULL END,
      amount_received_rm = CASE WHEN p_method = 'cash' AND v_total > 0 THEN p_received ELSE NULL END,
      paid_at = now(),
      paid_by_staff_id = p_staff_id,
      updated_at = now()
  WHERE id = p_sale_id
  RETURNING * INTO v_sale;

  RETURN v_sale;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.complete_counter_sale(UUID, UUID, TEXT, NUMERIC) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.complete_counter_sale(UUID, UUID, TEXT, NUMERIC) TO service_role;

-- 4. Lock down ----------------------------------------------------------------------
ALTER TABLE public.counter_sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.counter_sale_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.counter_sales, public.counter_sale_items FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.counter_sales, public.counter_sale_items TO service_role;
