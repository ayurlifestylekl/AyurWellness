-- Patient profile: patient ID, case sheets, photo attachments, visit remarks.
--
-- Server-only like public.patients: RLS on with no policies, so only the
-- service role (staff pages, after their role check) can read or write.
-- Safe to re-run.

-- 1. Patient ID ---------------------------------------------------------------
-- Shown as e.g. AWC-00012 and used as the case sheet's "Registration No".
-- BY DEFAULT (not ALWAYS) so records imported from Tunai Pro can keep their
-- old numbers. Existing rows are numbered when the column is added.
ALTER TABLE public.patients
  ADD COLUMN IF NOT EXISTS patient_no BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX IF NOT EXISTS patients_patient_no_key ON public.patients (patient_no);

-- 2. Case sheets ----------------------------------------------------------------
-- The doctors' two forms: one primary case sheet, then dated follow-up sheets.
-- The form fields live in `data` (see src/lib/staff/case-sheets.ts) so the
-- layout can follow the doctors' paper model without a column per box.
CREATE TABLE IF NOT EXISTS public.patient_case_sheets (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  patient_id          UUID NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
  kind                TEXT NOT NULL CHECK (kind IN ('primary', 'follow_up')),
  sheet_date          DATE NOT NULL DEFAULT ((now() AT TIME ZONE 'Asia/Kuala_Lumpur')::date),
  data                JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by_staff_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  updated_by_staff_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS patient_case_sheets_patient_idx
  ON public.patient_case_sheets (patient_id, sheet_date DESC, created_at DESC);

-- 3. Photo attachments ----------------------------------------------------------
-- Files live in the private "patient-photos" bucket; staff see them through
-- short-lived signed links only.
CREATE TABLE IF NOT EXISTS public.patient_photos (
  id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  patient_id           UUID NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
  storage_path         TEXT NOT NULL UNIQUE,
  taken_on             DATE NOT NULL DEFAULT ((now() AT TIME ZONE 'Asia/Kuala_Lumpur')::date),
  tag                  TEXT CHECK (tag IS NULL OR tag IN ('before', 'after', 'progress')),
  remark               TEXT CHECK (remark IS NULL OR char_length(remark) <= 500),
  uploaded_by_staff_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS patient_photos_patient_idx
  ON public.patient_photos (patient_id, taken_on DESC, created_at DESC);

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('patient-photos', 'patient-photos', false, 5242880, ARRAY['image/jpeg', 'image/png', 'image/webp'])
ON CONFLICT (id) DO NOTHING;

-- 4. Visit remarks ---------------------------------------------------------------
-- A visit's record is not editable; staff add dated remarks to it instead.
CREATE TABLE IF NOT EXISTS public.visit_remarks (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  appointment_id  UUID NOT NULL REFERENCES public.appointments(id) ON DELETE CASCADE,
  body            TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1000),
  author_staff_id UUID REFERENCES public.users(id) ON DELETE SET NULL,
  author_name     TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS visit_remarks_appointment_idx
  ON public.visit_remarks (appointment_id, created_at);

-- 5. Lock down -------------------------------------------------------------------
ALTER TABLE public.patient_case_sheets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.patient_photos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.visit_remarks ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.patient_case_sheets, public.patient_photos, public.visit_remarks FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.patient_case_sheets, public.patient_photos TO service_role;
GRANT SELECT, INSERT ON public.visit_remarks TO service_role;
